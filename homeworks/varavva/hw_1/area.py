def area() -> int:
  """
  Процедура вычисляет площадь прямоугольника по введенным данным
  Принимаются только целые числа
  Проверка ввода на корректность не проводится
  """
  a, b = input("Введите ширину и длину прямоугольника через пробел: ").split()
  a, b = int(a), int(b)
  return a*b
print(f"Площадь прямоугольника: {area()}")
